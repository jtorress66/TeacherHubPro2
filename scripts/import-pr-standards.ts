import { readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { extractText, getDocumentProxy } from 'unpdf';
import {
  documents,
  parseDocument,
  type ParsedStandard,
  type PrSubject,
} from './pr-standards/parse.ts';

// Reads the Puerto Rico Department of Education's standards documents (PDFs) once and writes
// their codes into the domain. Run with `pnpm standards:import-pr [--from <folder>]` (the folder
// holding the PDFs, by default Downloads); the output is checked in.

const output = 'packages/domain/src/standards/puerto-rico-codes.ts';

const sources: readonly { readonly subject: PrSubject; readonly file: string }[] = [
  { subject: 'english', file: 'Estándares y Expectativas Programa de Inglés.pdf' },
  { subject: 'spanish', file: 'espanol.pdf' },
  { subject: 'math', file: 'Estándares y Expectativas Programa de Matemáticas.pdf' },
  { subject: 'science', file: 'estandares_de_ciencias_2014.pdf' },
  { subject: 'social_studies', file: 'Estudios Sociales.pdf' },
];

/**
 * The Spanish document's text has no character map: each character comes out as its Calibri
 * glyph number. `pr-standards/calibri-glyphs.json` maps the glyphs it uses back to letters.
 */
const glyphDecoded: readonly PrSubject[] = ['spanish'];

export function decodeGlyphs(text: string, table: Readonly<Record<string, string>>): string {
  return text.replace(/[^ \n]/gu, (ch) => table[String(ch.codePointAt(0))] ?? ch);
}

export function renderPrCatalog(standards: readonly ParsedStandard[]): string {
  const rows = standards.map((s) =>
    JSON.stringify([s.code, s.subject, s.grades, s.level, s.course, s.strand, s.description]),
  );
  return [
    '// Generated by scripts/import-pr-standards.ts — do not edit by hand.',
    '// Estándares de Contenido y Expectativas de Grado, Departamento de Educación de Puerto Rico:',
    '// Inglés (2022), Matemáticas (2022), Español (2014), Ciencias (2014), Estudios Sociales (2014).',
    "import type { PrRow } from './puerto-rico.ts';",
    '',
    'export const puertoRicoRows: readonly PrRow[] = [',
    ...rows.map((row) => `  ${row},`),
    '];',
    '',
  ].join('\n');
}

async function pagesOf(path: string): Promise<string[]> {
  const pdf = await getDocumentProxy(new Uint8Array(readFileSync(path)));
  const { text } = await extractText(pdf, { mergePages: false });
  return text;
}

async function main(): Promise<void> {
  const at = process.argv.indexOf('--from');
  const folder = at >= 0 ? (process.argv[at + 1] ?? '') : join(homedir(), 'Downloads');
  const glyphs = JSON.parse(
    readFileSync(new URL('./pr-standards/calibri-glyphs.json', import.meta.url), 'utf8'),
  ) as Record<string, string>;
  const all: ParsedStandard[] = [];
  for (const { subject, file } of sources) {
    const raw = await pagesOf(join(folder, file));
    const pages = glyphDecoded.includes(subject)
      ? raw.map((page) => decodeGlyphs(page, glyphs))
      : raw;
    const { standards, skipped, notes } = parseDocument(pages, documents[subject]);
    process.stdout.write(
      `${subject}: ${String(standards.length)} codes, ${String(skipped.length)} left out, ${String(notes.length)} notes\n`,
    );
    for (const line of [...skipped, ...notes]) process.stdout.write(`  ${line}\n`);
    all.push(...standards);
  }
  writeFileSync(output, renderPrCatalog(all));
  process.stdout.write(`Wrote ${String(all.length)} codes to ${output}\n`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  await main();
}
