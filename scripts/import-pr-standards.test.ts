import { describe, expect, it } from 'vitest';
import { decodeGlyphs, renderPrCatalog } from './import-pr-standards.ts';

describe('decodeGlyphs', () => {
  it('turns a PDF’s glyph numbers back into letters, keeping spaces and unknown glyphs', () => {
    const table = { '400': 's', '410': 't', '260': 'á', '1005': '1' };
    const scrambled = String.fromCodePoint(400, 410, 260, 32, 1005, 9999);

    expect(decodeGlyphs(scrambled, table)).toBe(`stá 1${String.fromCodePoint(9999)}`);
  });
});

describe('renderPrCatalog', () => {
  it('writes the catalog as a typed module that names its sources, in a stable order', () => {
    const source = renderPrCatalog([
      {
        code: '7.R.6.1L',
        subject: 'english',
        grades: ['7'],
        level: null,
        course: null,
        strand: 'R',
        description: 'Explain how an author develops the point of view.',
      },
      {
        code: 'ES.Q.IT1.IT.1',
        subject: 'science',
        grades: [],
        level: 'high',
        course: 'Química',
        strand: 'Q',
        description: 'Identifica una “posible” solución.',
      },
    ]);

    expect(source).toContain(
      '// Generated by scripts/import-pr-standards.ts — do not edit by hand.',
    );
    expect(source).toContain('Departamento de Educación de Puerto Rico');
    expect(source).toContain("import type { PrRow } from './puerto-rico.ts';");
    expect(source).toContain(
      '  ["7.R.6.1L","english",["7"],null,null,"R","Explain how an author develops the point of view."],',
    );
    expect(source).toContain(
      '  ["ES.Q.IT1.IT.1","science",[],"high","Química","Q","Identifica una “posible” solución."],',
    );
  });
});
